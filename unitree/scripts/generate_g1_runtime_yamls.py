#!/usr/bin/env python3
"""Generate (or --check) the Unitree G1 MuJoCo runtime + action-adapter YAMLs from ``g1_actuation``.

Outputs (repo-relative):
  a3_deploy/a3_deploy_example/config/action_adapter_unitree_g1.yaml
      default_q / action_scale / joint_position_clamp — read by the training package
      (robot="unitree_g1") and by the reference runner / MuJoCo evaluator (RobotProfile UNITREE_G1)
  a3_deploy/a3_deploy_example/config/hope_pingpong_runtime_unitree_g1.yaml
      contract, control rate, MJCF path, PER-JOINT PD gains = the Isaac implicit-drive gains, and the
      lifecycle ready-reach values (G1-scaled, see docs/UNITREE_G1.md)

Everything numeric comes from ``unitree/scripts/g1_actuation.py`` (the pure-Python mirror of
``robots/g1.py``) and the upstream URDF joint limits, so the MuJoCo plant can never drift from the
Isaac one by hand-editing. ``tests/test_g1_mujoco_plant.py`` asserts the committed files equal a fresh
generation.

Usage (from the repo root): python3 unitree/scripts/generate_g1_runtime_yamls.py [--check]
"""

from __future__ import annotations

import argparse
import pathlib
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import g1_actuation  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parents[2]
JOINT_ORDER_YAML = REPO / "hope_training" / "config" / "joint_order_unitree_g1.yaml"
UPSTREAM_URDF = REPO / "unitree" / "URDF" / "g1_description" / "urdf" / "g1_29dof_rev_1_0.urdf"
ADAPTER_OUT = REPO / "a3_deploy" / "a3_deploy_example" / "config" / "action_adapter_unitree_g1.yaml"
RUNTIME_OUT = REPO / "a3_deploy" / "a3_deploy_example" / "config" / "hope_pingpong_runtime_unitree_g1.yaml"

#: Base-relative ready reach the racket goal holds while idle. A3 example values are
#: (0.40, 0.20, -0.05); the G1's shoulder-to-blade reach is 0.81x the A3's (0.59 m vs 0.73 m).
READY_REACH = (0.32, 0.16, -0.04)
LIFECYCLE = (("follow_through_s", 0.6), ("recovery_s", 0.8), ("ready_time_to_strike", 1.0))


def _fmt(x: float) -> str:
    return f"{x:.6g}"


def joint_order() -> list[str]:
    import yaml

    with open(JOINT_ORDER_YAML, "r", encoding="utf-8") as fh:
        return [str(n) for n in yaml.safe_load(fh)["joint_order"]]


def urdf_limits() -> dict[str, tuple[float, float]]:
    root = ET.parse(UPSTREAM_URDF).getroot()
    return {
        j.get("name"): (float(j.find("limit").get("lower")), float(j.find("limit").get("upper")))
        for j in root.findall("joint")
        if j.get("type") == "revolute"
    }


def render_adapter(order: list[str]) -> str:
    limits = urdf_limits()
    lines = [
        "# Canonical shared ActionAdapter configuration (HOPE, 29-DOF Unitree G1).",
        "#",
        "# GENERATED by unitree/scripts/generate_g1_runtime_yamls.py from unitree/scripts/g1_actuation.py",
        "# (the pure-Python mirror of robots/g1.py G1_CYLINDER_CFG) and the upstream URDF joint limits.",
        "# Do not edit by hand; tests/test_g1_mujoco_plant.py pins this file to a fresh generation.",
        "#",
        "# Mirror of action_adapter.yaml (Agibot A3) for the Unitree G1. Read by BOTH the training package",
        "# (whole_body_tracking.utils.action_adapter_config, robot=\"unitree_g1\") and the reference deploy",
        "# runner / MuJoCo evaluator (RobotProfile UNITREE_G1), so the raw-action -> joint-target mapping is",
        "# defined in exactly one place. Parity is asserted by",
        "# hope_training/whole_body_tracking/tests/test_action_adapter_parity_g1.py.",
        "#",
        "# Transform (deterministic; not a rejection filter, emits no status):",
        "#     q_des = default_q + raw_action * action_scale",
        "#     q_des = clip(q_des, joint_position_clamp.lower, joint_position_clamp.upper)",
        "#",
        "#   * default_q    : G1_CYLINDER_CFG.init_state.joint_pos (BeyondMimic G1 stand; unlisted joints 0).",
        "#   * action_scale : per joint, 0.25 * effort_limit_sim / stiffness == G1_ACTION_SCALE in robots/g1.py",
        "#                    (the recipe's 50 N.m ankle/waist effort, not the URDF's 35 N.m -- see g1.py).",
        "#   * joint_position_clamp : the upstream g1_29dof_rev_1_0 URDF joint limits.",
        "# The G1 has no passive (neck) columns: every vector here is length 29.",
        "",
        "action_scale:",
    ]
    lines += [f"  {n}: {_fmt(g1_actuation.action_scale(n))}" for n in order]
    lines += ["", "default_q:            # rad, BeyondMimic G1 stand (= Isaac articulation default pose)"]
    lines += [f"  {n}: {_fmt(g1_actuation.init_joint_pos(n))}" for n in order]
    lines += ["", "joint_position_clamp:  # rad; upstream g1_29dof_rev_1_0 URDF joint limits", "  lower:"]
    lines += [f"    {n}: {_fmt(limits[n][0])}" for n in order]
    lines += ["  upper:"]
    lines += [f"    {n}: {_fmt(limits[n][1])}" for n in order]
    return "\n".join(lines) + "\n"


def render_runtime(order: list[str]) -> str:
    lines = [
        "# HOPE runtime configuration -- Unitree G1 (29-DoF), 104-D `hitter_pure_unitree_g1`.",
        "#",
        "# GENERATED by unitree/scripts/generate_g1_runtime_yamls.py from unitree/scripts/g1_actuation.py;",
        "# do not edit by hand (tests/test_g1_mujoco_plant.py pins it to a fresh generation).",
        "#",
        "# Read by the clean-room reference runner (a3_deploy_onnx_ref_pingpong --robot unitree_g1) and by",
        "# hope_training/whole_body_tracking/scripts/mujoco_eval_onnx.py --robot unitree_g1. Every relative",
        "# path resolves against THIS file's directory. The A3 config (hope_pingpong_runtime.yaml) is untouched.",
        "#",
        "# Single observation/action path only: 104-D observation, 29-D action, no observation",
        "# normalization, one control rate, no passive columns (the G1 has no neck).",
        "",
        "contract: hitter_pure_unitree_g1",
        "control_hz: 50.0                 # 50 Hz control loop",
        "observation_normalization: none  # raw observation (must stay 'none')",
        "passive_neck: false              # the G1 has no passive joints",
        "",
        "policy:",
        "  # No published G1 policy ships with the repository: export one with",
        "  #   scripts/export_onnx.py --robot unitree_g1 --task HOPE-HitterPingPong-UnitreeG1-v0 ...",
        "  # and pass it with --onnx (or edit this path).",
        "  onnx_path: ../models/unitree_g1/policy/exported/policy.onnx",
        "  joint_order: unitree_g1        # LOAD-BEARING: selects the RobotProfile (joint names, dims, MJCF names)",
        "",
        "action_adapter:",
        "  config_path: action_adapter_unitree_g1.yaml",
        "",
        "simulation:",
        "  # The racket-equipped G1 MJCF generated from the vendored Unitree description (unitree/README.md).",
        "  model_xml_path: ../../../unitree/URDF/g1_29dof_pingpang/mjcf/g1_29dof_pingpang.xml",
        "  # Training-plant PD gains (G1_CYLINDER_CFG stiffness/damping in robots/g1.py), PER JOINT, so the",
        "  # MuJoCo harness realizes q_des the way the Isaac implicit drive did (the leg group alone spans",
        "  # 28.5 .. 99.1 N.m/rad, so group-averaged gains topple the robot). Not vendor deploy gains.",
        "  pd_gains:",
        "    per_joint:",
        "      stiffness:",
    ]
    lines += [f"        {n}: {_fmt(g1_actuation.stiffness(n))}" for n in order]
    lines += ["      damping:"]
    lines += [f"        {n}: {_fmt(g1_actuation.damping(n))}" for n in order]
    lines += [
        "",
        "lifecycle:",
        "  # Example continuous-rally timing (ready -> swing -> follow-through -> recovery).",
    ]
    lines += [f"  {k}: {_fmt(v)}" for k, v in LIFECYCLE]
    lines += [
        "  # Reference clock (D17 in docs/g1_forehand/decisions.md): show the policy strike_time - now from the",
        "  # planner's absolute deadline instead of counting the copied time_to_strike down one tick early.",
        "  # Needs planner and runner clocks synced; a command whose implied message age is negative or",
        "  # above max_message_age_s is stamped on receipt instead. The A3 config keeps countdown.",
        "  clock: strike_time",
        "  max_message_age_s: 0.1",
        "  # Timing calibration added to every command's time left (D17). +40 ms puts the strike on the",
        "  # apex in MuJoCo with the strike_time clock (cause still open); re-measure on the real robot.",
        "  tts_offset_s: 0.04",
    ]
    lines += [
        "  # Base-relative ready reach the racket goal holds while idle: the A3 example values",
        "  # (0.40, 0.20, -0.05) scaled by the G1/A3 shoulder-to-blade reach ratio 0.81 (docs/UNITREE_G1.md).",
        f"  ready_reach_x: {_fmt(READY_REACH[0])}",
        f"  ready_reach_y: {_fmt(READY_REACH[1])}",
        f"  ready_reach_z: {_fmt(READY_REACH[2])}",
    ]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Exit 1 if the committed files differ from a fresh generation.")
    args = parser.parse_args(argv)
    order = joint_order()
    outputs = {ADAPTER_OUT: render_adapter(order), RUNTIME_OUT: render_runtime(order)}
    if args.check:
        bad = [p for p, text in outputs.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        if bad:
            for p in bad:
                print(f"[generate_g1_runtime_yamls] STALE: {p.relative_to(REPO)} (regenerate: python3 unitree/scripts/generate_g1_runtime_yamls.py)")
            return 1
        print("[generate_g1_runtime_yamls] OK: committed YAMLs match a fresh generation")
        return 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
        print(f"[generate_g1_runtime_yamls] wrote {p.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
